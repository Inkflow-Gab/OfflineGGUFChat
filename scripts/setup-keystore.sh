#!/usr/bin/env bash
# Creates THE release keystore — once, forever.
#
# Android only installs an APK as an *update* (keeping the app's data: chats,
# models, settings) when the new APK is signed with the same key as the one
# already installed. So this project uses exactly one release keystore for
# every version, for ever:
#
#   1. Run this script once on your own machine.
#   2. Paste the four values it prints into GitHub → Settings → Secrets:
#         KEYSTORE_B64        (the whole keystore, base64-encoded)
#         KEYSTORE_PASSWORD   (the store password you choose below)
#         KEY_ALIAS           (printed by the script)
#         KEY_PASSWORD        (the key password — same prompt, see below)
#   3. Back up release.jks + the password somewhere safe (password manager,
#      encrypted drive). CI signs every future release with it, and every
#      future APK updates in place.
#
# If the keystore is ever lost, no new APK can update an installed one —
# users would have to uninstall (losing local data) and reinstall. Treat the
# backup like the master key it is. It is git-ignored and never committed.
#
# Usage:
#   ./scripts/setup-keystore.sh                 # prompts for passwords
#   KEYSTORE_PASSWORD=... KEY_PASSWORD=... ./scripts/setup-keystore.sh
#
# Re-running with an existing release.jks refuses to overwrite it. Pass
# --print-secrets to re-print the GitHub values for the existing keystore.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KEYSTORE="$ROOT/release.jks"
ALIAS="${KEY_ALIAS:-offlinegguf}"
PRINT_ONLY=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --print-secrets) PRINT_ONLY=1; shift ;;
    -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [[ ! -f "$KEYSTORE" && "$PRINT_ONLY" -eq 1 ]]; then
  echo "No keystore at $KEYSTORE yet — run without --print-secrets to create it." >&2
  exit 1
fi

if [[ -f "$KEYSTORE" && "$PRINT_ONLY" -eq 0 ]]; then
  cat >&2 <<EOF
$KEYSTORE already exists — refusing to overwrite it.

One keystore signs every release forever; replacing it would break updates
for everyone who has the app installed. If you only need the GitHub secret
values again, run:

    ./scripts/setup-keystore.sh --print-secrets
EOF
  exit 1
fi

if [[ "$PRINT_ONLY" -eq 0 ]]; then
  if ! command -v keytool >/dev/null 2>&1; then
    echo "keytool not found. Install a JDK 17 (same one Gradle uses) and retry." >&2
    exit 1
  fi

  # One password for both store and key keeps the one-time setup simple; the
  # two GitHub secrets simply hold the same value.
  if [[ -z "${KEYSTORE_PASSWORD:-}" ]]; then
    read -r -s -p "Choose a keystore password (min 8 chars, store it in a password manager): " KEYSTORE_PASSWORD; echo
    read -r -s -p "Repeat it: " CONFIRM; echo
    if [[ "$KEYSTORE_PASSWORD" != "$CONFIRM" ]]; then
      echo "Passwords do not match." >&2; exit 1
    fi
  fi
  if [[ ${#KEYSTORE_PASSWORD} -lt 8 ]]; then
    echo "Password too short (keytool requires at least 6; use 8+)." >&2; exit 1
  fi
  KEY_PASSWORD="${KEY_PASSWORD:-$KEYSTORE_PASSWORD}"

  echo "Generating a 4096-bit RSA key (valid 10000 days ≈ 27 years)…"
  keytool -genkeypair -v \
    -keystore "$KEYSTORE" \
    -alias "$ALIAS" \
    -keyalg RSA -keysize 4096 \
    -validity 10000 \
    -storepass "$KEYSTORE_PASSWORD" \
    -keypass "$KEY_PASSWORD" \
    -dname "CN=Offline GGUF Chat, OU=Releases, O=Inkflow-Gab" >/dev/null

  # Local release builds pick the same key up automatically.
  cat > "$ROOT/keystore.properties" <<EOF
# Generated by scripts/setup-keystore.sh — git-ignored, do not commit.
storeFile=release.jks
storePassword=$KEYSTORE_PASSWORD
keyAlias=$ALIAS
keyPassword=$KEY_PASSWORD
EOF
  echo "Wrote $ROOT/keystore.properties for local signed builds."
fi

KEYSTORE_PASSWORD="${KEYSTORE_PASSWORD:-<the password you chose>}"
KEY_PASSWORD="${KEY_PASSWORD:-$KEYSTORE_PASSWORD}"

B64="$(base64 -w 0 < "$KEYSTORE" 2>/dev/null || base64 < "$KEYSTORE" | tr -d '\n')"

cat <<EOF

=====================================================================
 Add these four repository secrets (GitHub → Settings → Secrets and
 variables → Actions → New repository secret). Do this ONCE; every
 release from then on is signed with this key and updates in place.
=====================================================================

KEYSTORE_B64
---------------------------------------------------------------------
$B64
---------------------------------------------------------------------

KEYSTORE_PASSWORD
---------------------------------------------------------------------
$KEYSTORE_PASSWORD
---------------------------------------------------------------------

KEY_ALIAS
---------------------------------------------------------------------
$ALIAS
---------------------------------------------------------------------

KEY_PASSWORD
---------------------------------------------------------------------
$KEY_PASSWORD
---------------------------------------------------------------------

Then back up these two things together, somewhere NOT in this repo:
  * $KEYSTORE
  * the password above

Fingerprint of the signing certificate (for your records):
EOF

if command -v keytool >/dev/null 2>&1 && [[ -n "${KEYSTORE_PASSWORD:-}" ]]; then
  keytool -list -v -keystore "$KEYSTORE" -alias "$ALIAS" \
    -storepass "$KEYSTORE_PASSWORD" 2>/dev/null | grep -E 'SHA256:|Valid from' || true
fi
echo
echo "Done. Tag a release (git tag v1.4.0 && git push --tags) and CI ships a signed APK."
